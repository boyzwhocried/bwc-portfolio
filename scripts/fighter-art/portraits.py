"""Generates the HUD portraits for the sandbox fighter (local tool, not shipped).

Each portrait is a 32x32 tone map of the same public-domain reference photo the in-game head uses
(photos live OUTSIDE the repo). Dark tones become ink, light tones paper (4x4 ordered dither),
and reddish tones (cap band, insignia) become vermilion. Output: art/portraits.ts plus a preview PNG.

Usage: python scripts/fighter-art/portraits.py <refs_dir> <preview_png>
"""
import os
import sys

from PIL import Image, ImageFilter, ImageOps

OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'lib', 'sandbox', 'fighter', 'art', 'portraits.ts')
SIZE = 40
RGB = {1: (0x1A, 0x1A, 0x1A), 2: (0xEC, 0xE7, 0xDE), 3: (0xE8, 0x4C, 0x28)}
CH = {1: 'i', 2: 'p', 3: 'v'}
BAYER4 = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]

# id -> (photo file, crop box in photo pixels, ink threshold, paper threshold)
PORTRAITS = {
    'si-penyadap': ('si-penyadap.jpg', (120, 40, 320, 240), 0.42, 0.64),
    'sang-ajudan': ('sang-ajudan.jpg', (75, 95, 355, 375), 0.34, 0.58),
}


def portrait(refs, fname, box, ink_t, paper_t):
    src = Image.open(os.path.join(refs, fname)).convert('RGB').crop(box)
    lum = ImageOps.autocontrast(src.convert('L').resize((SIZE * 4, SIZE * 4), Image.LANCZOS).filter(ImageFilter.UnsharpMask(6, 160, 2)), cutoff=2).resize((SIZE, SIZE), Image.LANCZOS)
    col = src.resize((SIZE, SIZE), Image.LANCZOS)
    g = [[2] * SIZE for _ in range(SIZE)]
    for y in range(SIZE):
        for x in range(SIZE):
            r, gg, b = col.getpixel((x, y))
            v = lum.getpixel((x, y)) / 255
            if r > 110 and r > 2.2 * gg and r > 2.2 * b:
                g[y][x] = 3
            elif v < ink_t:
                g[y][x] = 1
            elif v > paper_t:
                g[y][x] = 2
            else:
                f = (v - ink_t) / (paper_t - ink_t)
                g[y][x] = 2 if f > (BAYER4[y % 4][x % 4] + 0.5) / 16 else 1
    # 1px ink frame so the portrait sits cleanly in its plate
    for i in range(SIZE):
        g[0][i] = g[SIZE - 1][i] = g[i][0] = g[i][SIZE - 1] = 1
    return g


def ts(g):
    return '{ w: %d, h: %d, rows: [\n' % (SIZE, SIZE) + ''.join("    '%s',\n" % ''.join(CH[v] for v in row) for row in g) + '  ] }'


def main():
    refs, preview = sys.argv[1], sys.argv[2]
    lines = ["import type { Sprite } from './sprite'", '', '// Generated by scripts/fighter-art/portraits.py. Do not edit by hand.', '', 'export const PORTRAITS: Record<string, Sprite> = {']
    sheet = Image.new('RGB', (SIZE * 10 * len(PORTRAITS) + 20 * (len(PORTRAITS) + 1), SIZE * 10 + 40), (0x70, 0x70, 0x70))
    for n, (fid, (fname, box, a, b)) in enumerate(PORTRAITS.items()):
        g = portrait(refs, fname, box, a, b)
        lines.append("  '%s': %s," % (fid, ts(g)))
        im = Image.new('RGB', (SIZE, SIZE))
        for y in range(SIZE):
            for x in range(SIZE):
                im.putpixel((x, y), RGB[g[y][x]])
        sheet.paste(im.resize((SIZE * 10, SIZE * 10), Image.NEAREST), (20 + n * (SIZE * 10 + 20), 20))
    lines.append('}')
    with open(OUT, 'w', newline='\n') as fh:
        fh.write('\n'.join(lines) + '\n')
    sheet.save(preview)
    print('wrote portraits + preview', preview)


if __name__ == '__main__':
    main()
